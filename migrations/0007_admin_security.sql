-- (تبويب「セキュリティ」)، بدل الاعتماد فقط على متغيّرات بيئة ADMIN_PASSWORD/ADMIN_TOTP_SECRET
-- (اللي لا يقدر أي Cloudflare Function يعدّلها من نفسه). الصق هذا بالكامل في D1 Console
-- وشغّله مرة واحدة (بعد تنفيذ 0001~0006 مسبقًا).

-- admin_password_hash: فارغ = استخدم env.ADMIN_PASSWORD كما هو الحال اليوم (بلا تغيير).
--   بمجرد تغيير كلمة المرور من تبويب「セキュリティ」، تُخزَّن هنا (PBKDF2 + salt عشوائي،
--   صيغة "saltHex:hashHex") وتصبح هي المعتمدة دائمًا بدل env.ADMIN_PASSWORD.
-- admin_totp_secret: فارغ = لا يوجد تحقق بخطوتين (سلوك اليوم). بعد "追加" ثم إدخال
--   الرمز الصحيح من تطبيق المصادقة، يُخزَّن هنا ويصبح 2FA مفعّلاً فورًا.
-- admin_totp_pending: مفتاح TOTP مؤقت أثناء عملية الإعداد فقط (بين "追加" وتأكيد الرمز) —
--   لا يُستخدم لتسجيل الدخول أبدًا، فقط لتفادي قفل الدخول لو فشل الإعداد في المنتصف.
